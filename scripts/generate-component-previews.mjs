// Writes src/lib/component-previews.generated.ts — a static import map of every
// `*.preview.tsx` file under src/components. next.config.ts runs this on every
// `next dev` / `next build` (plus `--watch` during dev); you can also run it by hand:
//
//   node scripts/generate-component-previews.mjs [--watch]
//
// The file is only rewritten when its contents would change.

import {
  existsSync,
  readdirSync,
  readFileSync,
  watch,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const componentsDir = path.join(root, "src", "components");
const outputFile = path.join(root, "src", "lib", "component-previews.generated.ts");

const PREVIEW_SUFFIX = ".preview.tsx";

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

function toPosix(p) {
  return p.split(path.sep).join("/");
}

export function generateComponentPreviews() {
  const previews = walk(componentsDir)
    .filter((file) => file.endsWith(PREVIEW_SUFFIX))
    .map((file) => toPosix(path.relative(componentsDir, file)))
    .sort();

  const imports = previews.map(
    (file, i) =>
      `import * as preview${i} from "@/components/${file.slice(0, -".tsx".length)}";`,
  );
  const entries = previews.map(
    (file, i) =>
      `  "${file.slice(0, -PREVIEW_SUFFIX.length)}.tsx": preview${i},`,
  );

  const contents = [
    "// Generated by scripts/generate-component-previews.mjs — do not edit by hand.",
    "// Maps a component file (relative to src/components) to its *.preview.tsx module.",
    "",
    'import type { ComponentPreviewModule } from "@/lib/component-preview";',
    ...imports,
    "",
    "export const componentPreviews: Record<string, ComponentPreviewModule> = {",
    ...entries,
    "};",
    "",
  ].join("\n");

  if (existsSync(outputFile) && readFileSync(outputFile, "utf8") === contents) {
    return false;
  }
  writeFileSync(outputFile, contents);
  return true;
}

const invokedDirectly =
  process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (generateComponentPreviews()) {
    console.log("[components] preview map updated");
  }

  if (process.argv.includes("--watch")) {
    let timer;
    watch(componentsDir, { recursive: true }, (_event, filename) => {
      if (!filename || !String(filename).endsWith(PREVIEW_SUFFIX)) return;
      clearTimeout(timer);
      timer = setTimeout(() => {
        if (generateComponentPreviews()) {
          console.log("[components] preview map updated");
        }
      }, 100);
    });
  }
}
